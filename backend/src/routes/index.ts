import { Router } from 'express';
import { rateLimit, ipKeyGenerator } from 'express-rate-limit';
import { z } from 'zod';
import * as auth from '../controllers/auth.controller.js';
import * as courses from '../controllers/courses.controller.js';
import * as announcements from '../controllers/announcements.controller.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
import { validatePagination } from '../middleware/pagination.js';
import { adminCreateUser } from '../services/auth.service.js';
import type { RequestHandler } from 'express';

const router=Router();
const keyFor=(req: import('express').Request)=>`${ipKeyGenerator(req.ip??'127.0.0.1')}:${String(req.body?.email??'').toLowerCase()}`;
const loginLimiter=rateLimit({windowMs:15*60*1000,limit:5,standardHeaders:'draft-8',legacyHeaders:false,keyGenerator:keyFor});
const forgotLimiter=rateLimit({windowMs:60*60*1000,limit:3,standardHeaders:'draft-8',legacyHeaders:false,keyGenerator:keyFor});
const noStore:RequestHandler=(_req,res,next)=>{res.setHeader('Cache-Control','no-store');next();};
router.post('/auth/login',loginLimiter,noStore,auth.login);
router.post('/auth/refresh',noStore,auth.refresh);
router.post('/auth/logout',auth.logout);
router.post('/auth/forgot-password',forgotLimiter,auth.forgotPassword);
router.post('/auth/reset-password',auth.resetPassword);
router.get('/auth/session',requireAuth,auth.session);
router.get('/auth/me',requireAuth,auth.session);
router.post('/auth/change-password',requireAuth,auth.changePassword);
router.patch('/me/profile',requireAuth,auth.updateProfile);
router.get('/courses',requireAuth,validatePagination,courses.list);
router.get('/announcements',requireAuth,validatePagination,announcements.list);
const createUserSchema=z.object({email:z.string().email().max(254),fullName:z.string().trim().min(2).max(100),role:z.enum(['teacher','student']),rollNo:z.string().trim().max(32).optional()});
router.post('/admin/users',requireAuth,requireRole('admin'),async(req,res,next)=>{try{const input=createUserSchema.parse(req.body);const data=await adminCreateUser(input);res.status(201).json({data});}catch(e){next(e);}});
export default router;
